package vt

import (
	"encoding/json"
	"math/rand"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// Cross-implementation fixtures.
//
// The grid model is implemented twice: here in Go for the daemon, and in Rust
// for the mobile client. Two implementations of one wire format drift apart
// silently -- the symptom is a phone rendering something the daemon never had,
// which is close to impossible to debug from a bug report.
//
// This generates a fixture file the Rust side replays: a sequence of terminal
// writes, and after each one the snapshot, the delta, and the resulting screen
// text. The Rust implementation must reproduce every step exactly.
//
// Run with: go test ./internal/vt/ -run TestGenerateCrossImplFixtures -update-fixtures

const crossImplFixture = "../../../fixtures/vt/cross-impl.json"

// Step is one write and everything the other implementation must reproduce.
type Step struct {
	// Input is the raw bytes written to the emulator, base64 to survive JSON.
	Input string `json:"input_b64"`
	// Snapshot is the full grid after the write.
	Snapshot Snapshot `json:"snapshot"`
	// Delta is the change from the previous step.
	Delta []RowRuns `json:"delta"`
	// Text is the rendered screen, as a readable cross-check that fails
	// legibly when the cell-level comparison fails.
	Text string `json:"text"`
	// CursorX and CursorY are called out separately because an off-by-one
	// cursor is invisible in the text but wrong on screen.
	CursorX int `json:"cursor_x"`
	CursorY int `json:"cursor_y"`
}

// CrossImplFixture is the whole file.
type CrossImplFixture struct {
	Comment string `json:"_comment"`
	Cols    int    `json:"cols"`
	Rows    int    `json:"rows"`
	Steps   []Step `json:"steps"`
}

func TestGenerateCrossImplFixtures(t *testing.T) {
	if os.Getenv("MUXSCALE_UPDATE_FIXTURES") == "" {
		t.Skip("set MUXSCALE_UPDATE_FIXTURES=1 to regenerate")
	}

	const cols, rows = 40, 12
	e := NewEmulator(cols, rows)
	prev := e.Grid().Clone()

	fixture := CrossImplFixture{
		Comment: "Generated by go test ./internal/vt -run TestGenerateCrossImplFixtures. " +
			"The Rust client core replays these and must reproduce every snapshot, " +
			"delta and cursor position exactly. Two implementations of one wire " +
			"format drift apart silently; this is what catches it.",
		Cols: cols, Rows: rows,
	}

	// A deliberately awkward script: colour, cursor motion, erase, scrolling,
	// wide runes, overwriting half a wide rune, alternate screen, and a line
	// that exactly fills the width to exercise deferred wrap.
	writes := []string{
		"hello world",
		"\r\n",
		"\x1b[1;32mgreen bold\x1b[0m plain",
		"\r\n\x1b[38;5;208m256-colour\x1b[0m",
		"\r\n\x1b[38;2;10;20;30mtruecolour\x1b[0m",
		"\r\n\x1b[41mred background    \x1b[0m",
		"\r\n日本語 wide runes",
		"\x1b[7;1Hx", // overwrite the first half of a wide rune
		"\r\n\x1b[4munderline\x1b[0m",
		"\x1b[3;5H",                        // absolute cursor move
		"OVER",                             // overwrite mid-screen
		"\x1b[K",                           // erase to end of line
		"\r\n" + strings.Repeat("f", cols), // exactly fills the row: deferred wrap
		"g",                                // ...now it wraps
		"\x1b[2;3r",                        // scroll region
		"\x1b[10;1H",
		"\r\n\r\n\r\n", // force scrolling
		"\x1b[r",       // reset scroll region
		"\x1b[?1049h",  // alternate screen
		"alt screen content\r\nsecond line",
		"\x1b[?1049l",   // back to main
		"\x1b[2J\x1b[H", // clear and home
		"after clear",
		"\x1b[1L", // insert line
		"\x1b[1M", // delete line
		"tab\there",
		"\x1b[5D-----", // cursor back then overwrite
	}

	// Plus deterministic pseudo-random noise, which is where the interesting
	// disagreements have historically been.
	rng := rand.New(rand.NewSource(42))
	frags := []string{
		"\x1b[0m", "\x1b[1m", "\x1b[31m", "\x1b[42m", "\r\n", "\r", "\b",
		"abc", "é", "日", "\x1b[2K", "\x1b[1;1H", "\x1b[3C", "\x1b[1B",
	}
	for i := 0; i < 40; i++ {
		var sb strings.Builder
		for j := 0; j < rng.Intn(4)+1; j++ {
			sb.WriteString(frags[rng.Intn(len(frags))])
		}
		writes = append(writes, sb.String())
	}

	for _, w := range writes {
		if _, err := e.Write([]byte(w)); err != nil {
			t.Fatal(err)
		}
		g := e.Grid()
		fixture.Steps = append(fixture.Steps, Step{
			Input:    b64(w),
			Snapshot: g.Snapshot(),
			Delta:    g.Diff(prev),
			Text:     g.Text(),
			CursorX:  g.CursorX,
			CursorY:  g.CursorY,
		})
		prev = g.Clone()
	}

	if err := os.MkdirAll(filepath.Dir(crossImplFixture), 0o755); err != nil {
		t.Fatal(err)
	}
	out, err := json.MarshalIndent(fixture, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(crossImplFixture, append(out, '\n'), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %d steps to %s", len(fixture.Steps), crossImplFixture)
}

// The Go side must reproduce its own fixture, which catches an accidental
// change to the emulator or the wire encoding before the Rust side ever sees
// it.
func TestGoReproducesCrossImplFixture(t *testing.T) {
	data, err := os.ReadFile(crossImplFixture)
	if os.IsNotExist(err) {
		t.Skip("fixture not generated yet")
	}
	if err != nil {
		t.Fatal(err)
	}
	var fixture CrossImplFixture
	if err := json.Unmarshal(data, &fixture); err != nil {
		t.Fatal(err)
	}

	e := NewEmulator(fixture.Cols, fixture.Rows)
	// A replica built only from snapshots and deltas, exactly as a client does.
	replica := NewGrid(fixture.Cols, fixture.Rows)
	prev := e.Grid().Clone()

	for i, step := range fixture.Steps {
		input, err := unb64(step.Input)
		if err != nil {
			t.Fatalf("step %d: %v", i, err)
		}
		if _, err := e.Write(input); err != nil {
			t.Fatal(err)
		}
		g := e.Grid()

		if got := g.Text(); got != step.Text {
			t.Fatalf("step %d: screen text diverged\n got: %q\nwant: %q", i, got, step.Text)
		}
		if g.CursorX != step.CursorX || g.CursorY != step.CursorY {
			t.Fatalf("step %d: cursor = (%d,%d), want (%d,%d)",
				i, g.CursorX, g.CursorY, step.CursorX, step.CursorY)
		}

		// Applying the recorded delta must bring the replica to the same state.
		replica.ApplyDelta(Delta{
			Cols: fixture.Cols, Rows: fixture.Rows,
			CursorX: step.CursorX, CursorY: step.CursorY,
			Lines: step.Delta,
		})
		if !gridsEqual(g, replica) {
			t.Fatalf("step %d: the replica diverged from the emulator after applying the delta", i)
		}
		prev = g.Clone()
	}
	_ = prev
	t.Logf("reproduced %d fixture steps", len(fixture.Steps))
}
