package e2e

import (
	"encoding/hex"
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

// Generates the routing-header conformance fixture that the TypeScript relay
// replays.
//
// The protocol is implemented three times -- Go, Rust, TypeScript -- and §15.1
// gives that as the dominant reason this is a monorepo. Rust takes the header
// as opaque bytes so it needs no fixture; TypeScript re-derives the encoding
// and therefore does.
//
// Go is the generator because it is the reference implementation. The
// alternative -- each side asserting its own expected bytes -- is two
// independent guesses that agree until someone edits one of them.
//
// Regenerate with:
//
//	go test ./internal/e2e -run TestGenerateHeaderFixtures -update

var updateFixtures = os.Getenv("MUXSCALE_UPDATE_FIXTURES") != ""

type headerFixture struct {
	Name     string `json:"name"`
	Version  uint8  `json:"version"`
	HostKey  string `json:"host_key"`
	DeviceID string `json:"device_id"`
	StreamID uint32 `json:"stream_id"`
	// Encoded is the hex of the bytes bound into the AEAD.
	Encoded string `json:"encoded_hex"`
}

func headerFixtureCases() []RoutingHeader {
	return []RoutingHeader{
		{Version: 1, HostKey: "hk_abc", DeviceID: "dev_1", StreamID: 0},
		{Version: 1, HostKey: "hk_abc", DeviceID: "dev_1", StreamID: 1},
		{Version: 1, HostKey: "hk_abc", DeviceID: "dev_1", StreamID: 4294967295},
		{Version: 255, HostKey: "hk", DeviceID: "d", StreamID: 7},
		// Empty identifiers: legal to encode, and the pair that the old
		// delimited encoding could not distinguish.
		{Version: 1, HostKey: "", DeviceID: "a", StreamID: 2},
		{Version: 1, HostKey: "a", DeviceID: "", StreamID: 2},
		// Separator-bearing identifiers, the original ambiguity.
		{Version: 1, HostKey: "hk_a|dev_b", DeviceID: "dev_c", StreamID: 1},
		{Version: 1, HostKey: "hk_a", DeviceID: "dev_b|dev_c", StreamID: 1},
		// Non-ASCII, to pin that lengths are counted in bytes and not runes.
		{Version: 1, HostKey: "hôte_é", DeviceID: "appareil_ü", StreamID: 3},
		{Version: 1, HostKey: "主机", DeviceID: "设备", StreamID: 9},
		// A NUL inside an identifier must not terminate anything.
		{Version: 1, HostKey: "hk\x00x", DeviceID: "dev\x00y", StreamID: 4},
	}
}

func TestGenerateHeaderFixtures(t *testing.T) {
	cases := headerFixtureCases()
	out := make([]headerFixture, 0, len(cases))
	for i, h := range cases {
		if err := h.Valid(); err != nil {
			t.Fatalf("case %d is not encodable: %v", i, err)
		}
		out = append(out, headerFixture{
			Name:     h.HostKey + "/" + h.DeviceID,
			Version:  h.Version,
			HostKey:  h.HostKey,
			DeviceID: h.DeviceID,
			StreamID: h.StreamID,
			Encoded:  hex.EncodeToString(h.Encode()),
		})
	}

	// Distinct inputs must produce distinct bytes, or the fixture would be
	// pinning the very collision it exists to prevent.
	seen := map[string]int{}
	for i, f := range out {
		if j, dup := seen[f.Encoded]; dup {
			t.Fatalf("cases %d and %d encode identically to %s", j, i, f.Encoded)
		}
		seen[f.Encoded] = i
	}

	body, err := json.MarshalIndent(map[string]any{
		"//":      "Generated by go test ./internal/e2e -run TestGenerateHeaderFixtures. Do not edit.",
		"headers": out,
	}, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	body = append(body, '\n')

	path := filepath.Join("..", "..", "..", "fixtures", "protocol", "routing-header.json")
	existing, readErr := os.ReadFile(path)

	if readErr == nil && string(existing) == string(body) {
		return // already current
	}
	if readErr == nil && !updateFixtures {
		t.Fatalf("%s is stale.\n"+
			"The header encoding changed, which is a wire-protocol change that the "+
			"TypeScript relay replays.\nRegenerate deliberately:\n"+
			"    MUXSCALE_UPDATE_FIXTURES=1 go test ./internal/e2e -run TestGenerateHeaderFixtures",
			path)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, body, 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %s (%d headers)", path, len(out))
}
