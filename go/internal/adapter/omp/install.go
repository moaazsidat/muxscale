package omp

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// The extension is how omp tells muxscale it started or finished a turn.
//
// omp auto-discovers modules in <agentDir>/extensions, so installation is one
// file and no settings edit. It carries the loopback URL and token because the
// extension is plain JavaScript in a separate runtime and has no other way to
// learn them; the file is 0600, like the token file it duplicates.
//
// The read half of the adapter works without this file. Installing it only
// raises state confidence from a capped guess to the agent's own word.
const extensionMarker = "// muxscale:omp-extension v1"

// DefaultHookURL is the daemon's default loopback address.
const DefaultHookURL = "http://127.0.0.1:4455"

// ExtensionPath is where omp auto-discovers user extensions.
func ExtensionPath() (string, error) {
	d, err := agentDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(d, "extensions", "muxscale.ts"), nil
}

// ExtensionSource is the module written to disk.
//
// It registers lifecycle events and omp's approval prompts. Tool activity
// already arrives through the transcript, and forwarding it here would show
// every call twice; tool_call is only remembered, so an approval can name what
// it is for. A non-terminal agent_end is ignored: omp uses it for maintenance
// and async delivery, and treating that as a finished turn is the false "needs
// you" notification this product cannot afford.
//
// Approval events are omp's tool_approval_requested and _resolved, which only
// report: omp shows its own prompt either way, and an answer from a phone is
// typed into it (approve.go). Nothing here waits, so muxscale can never hold up
// or change a prompt.
func ExtensionSource(baseURL, token string) string {
	baseURL = strings.TrimRight(baseURL, "/")
	if baseURL == "" {
		baseURL = DefaultHookURL
	}
	return fmt.Sprintf(`%s
// Generated by muxscale. Removed by "muxscale down".
const MUXSCALE_URL = %q;
const MUXSCALE_TOKEN = %q;

export default function muxscale(pi: any): void {
  function sessionOf(ctx: any): any {
    let file = "";
    let id = "";
    try { file = ctx?.sessionManager?.getSessionFile?.() ?? ""; } catch {}
    try { id = ctx?.sessionManager?.getSessionId?.() ?? ""; } catch {}
    return { session_file: file, session_id: id, cwd: ctx?.cwd ?? "" };
  }

  async function send(event: string, ctx: any, extra?: any): Promise<void> {
    try {
      // omp rebinds extension factories to subagent sessions too. A subagent
      // is activity inside a parent session, not a session of its own; its
      // hook events would create a second row for one conversation.
      if (ctx?.agent?.kind === "sub") return;
      const payload = {
        v: 1,
        agent: "omp",
        event,
        ts: new Date().toISOString(),
        ...sessionOf(ctx),
        ...(extra ?? {}),
      };
      await fetch(MUXSCALE_URL + "/v1/hook/omp", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: "Bearer " + MUXSCALE_TOKEN,
        },
        body: JSON.stringify(payload),
        signal: AbortSignal.timeout(750),
      });
    } catch {
      // Fail open in the strongest sense: muxscale being down, slow, or
      // misconfigured must never change what omp does.
    }
  }

  function post(event: string, ctx: any, extra?: any): void {
    void send(event, ctx, extra);
  }

  function on(name: string, fn: (event: any, ctx: any) => void): void {
    try {
      pi.on(name, async (event: any, ctx: any) => {
        try { fn(event, ctx); } catch {}
      });
    } catch {}
  }

  on("session_start", (_e, ctx) => post("session_start", ctx));
  on("agent_start", (_e, ctx) => post("agent_start", ctx));

  on("agent_end", (e, ctx) => {
    // omp sets isTerminal: false when maintenance or async work will resume
    // the session. An absent field is terminal for older builds.
    if (e && e.isTerminal === false) return;
    post("agent_end", ctx, { is_terminal: true });
  });

  // The arguments of recent calls, so an approval prompt can say what it is
  // for: omp's approval events carry only the tool's name.
  const calls = new Map<string, any>();
  on("tool_call", (e, _ctx) => {
    if (!e?.toolCallId) return;
    calls.set(e.toolCallId, e.input ?? {});
    if (calls.size > 64) calls.delete(calls.keys().next().value);
  });

  // A prompt's close is sent only after its open has landed, so muxscale can
  // never see a prompt close before it opened and keep a card for it.
  const asked = new Map<string, Promise<void>>();
  on("tool_approval_requested", (e, ctx) => {
    const id = e?.toolCallId ?? "";
    asked.set(id, send("approval_requested", ctx, {
      tool_name: e?.toolName ?? "",
      tool_use_id: id,
      tool_input: calls.get(id) ?? {},
      reason: e?.reason ?? "",
    }));
  });
  on("tool_approval_resolved", (e, ctx) => {
    const id = e?.toolCallId ?? "";
    const opened = asked.get(id) ?? Promise.resolve();
    asked.delete(id);
    void opened.then(() => send("approval_resolved", ctx, {
      tool_name: e?.toolName ?? "",
      tool_use_id: id,
      approved: e?.approved === true,
      reason: e?.reason ?? "",
    }));
  });

  // session_shutdown has a 2s budget and may be the last code this process
  // runs, so this one is awaited rather than fire-and-forget.
  try {
    pi.on("session_shutdown", async (_e: any, ctx: any) => { await send("session_shutdown", ctx); });
  } catch {}
}
`, extensionMarker, baseURL, token)
}

// EnsureExtension writes the extension when it is absent or out of date.
//
// Returns true when it changed the file. A file at that path without our
// marker belongs to someone else and is never overwritten: the user's agent
// config is theirs, muxscale is a guest in it.
func EnsureExtension(baseURL, token string) (bool, error) {
	path, err := ExtensionPath()
	if err != nil {
		return false, err
	}
	want := ExtensionSource(baseURL, token)
	if cur, err := os.ReadFile(path); err == nil {
		if string(cur) == want {
			return false, nil
		}
		if !strings.Contains(string(cur), extensionMarker) {
			return false, fmt.Errorf("%s exists and was not written by muxscale; leaving it alone", path)
		}
	} else if !os.IsNotExist(err) {
		return false, err
	}

	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return false, err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".muxscale-*.tmp")
	if err != nil {
		return false, err
	}
	name := tmp.Name()
	defer os.Remove(name)
	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return false, err
	}
	if _, err := tmp.WriteString(want); err != nil {
		tmp.Close()
		return false, err
	}
	if err := tmp.Close(); err != nil {
		return false, err
	}
	if err := os.Rename(name, path); err != nil {
		return false, err
	}
	return true, nil
}

// ExtensionPresent reports whether a muxscale-written extension exists,
// without knowing the token it was written with. Uninstall and status use it.
func ExtensionPresent() bool {
	path, err := ExtensionPath()
	if err != nil {
		return false
	}
	b, err := os.ReadFile(path)
	return err == nil && strings.Contains(string(b), extensionMarker)
}

// ExtensionInstalled reports whether the current extension is on disk.
func ExtensionInstalled(baseURL, token string) bool {
	path, err := ExtensionPath()
	if err != nil {
		return false
	}
	b, err := os.ReadFile(path)
	if err != nil || !strings.Contains(string(b), extensionMarker) {
		return false
	}
	return string(b) == ExtensionSource(baseURL, token)
}

// RemoveExtension deletes the file only if muxscale wrote it.
func RemoveExtension() (bool, error) {
	path, err := ExtensionPath()
	if err != nil {
		return false, err
	}
	b, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, err
	}
	if !strings.Contains(string(b), extensionMarker) {
		return false, fmt.Errorf("%s was not written by muxscale; leaving it alone", path)
	}
	if err := os.Remove(path); err != nil {
		return false, err
	}
	return true, nil
}
